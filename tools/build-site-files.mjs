/**
 * Writes the site-wide files web hosts and search engines read:
 *   cpanel/htaccess-rules.txt  for cPanel: the block to paste at the top of the site folder's .htaccess
 *   site/_redirects            the same redirects for Cloudflare Pages (if ever used)
 *   site/sitemap.xml           every public page
 *   site/robots.txt
 * Redirects send old WordPress addresses to their new pages, so Google results and shared links keep working.
 * Run after adding pages or articles:
 *   npm run site-files
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SITE } from './page.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const site = join(here, '..', 'site');

/* ---------- Redirects ---------- */

const rules = [
  // WordPress's own shortcuts to its admin, which the owner uses for WooCommerce.
  ['/admin/', '/wp-admin/', 302],
  ['/dashboard/', '/wp-admin/', 302],
  ['/login/', '/wp-login.php', 302],
  ['/home/', '/', 301],
  ['/refund_returns/', '/refund-policy/', 301],
  ['/products/', '/shop/', 301],
  ['/organic-vegetables/', '/shop/?category=44', 301],
  ['/organic-fruits/', '/shop/?category=46', 301],
  ['/organic-meat-2/', '/shop/', 301],
  ['/product-category/*', '/shop/', 301],
  ['/product-tag/*', '/shop/', 301],
  // Old WooCommerce product pages, e.g. /product/wild-honey/ → a shop search for "wild honey".
  ['/product/:slug/', '/shop/?q=:slug', 302],
  // The old WooCommerce account and order-received pages. /checkout/ itself is the new checkout.
  ['/my-account/*', '/cart/', 302],
  ['/checkout/order-received/*', '/shop/', 302],
];

const articleFile = join(here, 'article-redirects.json');
if (existsSync(articleFile)) {
  for (const [from, to] of JSON.parse(readFileSync(articleFile, 'utf8'))) rules.push([from, to, 301]);
}

// The old site's 94 product write-up posts (e.g. /wild-honey/) → a shop search for that product.
const posts = [];
for (let page = 1; ; page++) {
  const res = await fetch(`https://www.sreevaaraahifarms.in/wp-json/wp/v2/posts?per_page=100&page=${page}&_fields=slug,link`);
  if (!res.ok) break;
  const batch = await res.json();
  posts.push(...batch);
  if (batch.length < 100) break;
}
// Sorted, so the file only changes when the redirects themselves do.
for (const post of posts.sort((x, y) => x.slug.localeCompare(y.slug))) {
  const path = new URL(post.link).pathname;
  // "+" for spaces: valid in a query and safe in Apache rules (where "%2" would mean something else).
  const query = post.slug.replace(/-\d+$/, '').replace(/[^a-z0-9]+/gi, '+');
  rules.push([path, `/shop/?q=${query}`, 301]);
}

/* ---------- cPanel (.htaccess) ---------- */

const regex = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function apacheRule([from, to, code]) {
  if (from === '/product/:slug/') {
    // Old WooCommerce product pages; /product/index.html itself is the new product page.
    return `RewriteCond %{REQUEST_FILENAME} !-f\nRewriteRule ^product/([^/]+)/?$ /shop/?q=$1 [R=${code},L]`;
  }
  if (from.endsWith('/*')) return `RewriteRule ^${regex(from.slice(1, -2))}(/.*)?$ ${to} [R=${code},L]`;
  const path = from.slice(1).replace(/\/$/, '');
  return path ? `RewriteRule ^${regex(path)}/?$ ${to} [R=${code},L]` : '';
}

const htaccess = `# BEGIN Sree Vaaraahi Farms website
# Paste this whole block at the very TOP of .htaccess in the website's folder (in cPanel:
# File Manager → sreevaaraahifarms.in), above "# BEGIN WordPress"
# and any other blocks. Generated by tools/build-site-files.mjs.
#
# The website's files sit in that folder next to WordPress. WordPress keeps running /wp-admin,
# the shop API (/wp-json) and the product photos (/wp-content); visitors see the new website.
# To go back to the old WordPress site: delete this block and index.html.
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# Always https://www.sreevaaraahifarms.in
RewriteCond %{HTTP_HOST} ^sreevaaraahifarms\\.in$ [NC]
RewriteRule ^ https://www.sreevaaraahifarms.in%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]

# Old WordPress addresses -> new pages
${rules.map(apacheRule).filter(Boolean).join('\n')}

# Anything else that isn't a real file or folder, and isn't WordPress's own admin, API or files,
# shows the website's 404 page instead of the old WordPress theme.
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteCond %{REQUEST_URI} !^/(wp-admin|wp-includes|wp-content|wp-json|wc-api|\\.well-known)(/|$) [NC]
RewriteCond %{REQUEST_URI} !^/(index|wp-login|wp-cron|xmlrpc|wp-comments-post|wp-signup|wp-activate|wp-trackback)\\.php$ [NC]
RewriteCond %{QUERY_STRING} !(^|&)(rest_route|wc-ajax|wc-api)= [NC]
RewriteRule ^ - [R=404,L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
# Pages, scripts and styles: browsers check for a newer copy each time, so updates show at once.
<FilesMatch "\\.(html|js|css)$">
Header set Cache-Control "no-cache"
</FilesMatch>
<FilesMatch "\\.(webp|png|jpe?g|svg|ico)$">
Header set Cache-Control "public, max-age=604800"
</FilesMatch>
</IfModule>
# END Sree Vaaraahi Farms website
`;
const cpanelDir = join(here, '..', 'cpanel');
mkdirSync(cpanelDir, { recursive: true });
writeFileSync(join(cpanelDir, 'htaccess-rules.txt'), htaccess);
console.log(`cpanel/htaccess-rules.txt: ${rules.length} redirects`);

writeFileSync(
  join(site, '_redirects'),
  `# Old WordPress addresses → new pages. Generated by tools/build-site-files.mjs\n${rules
    .map(([from, to, code]) => `${from} ${to} ${code}`)
    .join('\n')}\n`,
);
console.log(`_redirects: ${rules.length} rules (${posts.length} old posts)`);

/* ---------- Sitemap ---------- */

function* pages(dir) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      if (entry !== 'assets') yield* pages(path);
    } else if (entry === 'index.html') {
      yield path;
    }
  }
}

const urls = [];
for (const file of pages(site)) {
  const html = readFileSync(file, 'utf8');
  if (/<meta name="robots" content="noindex">/.test(html)) continue;
  const rel = relative(site, file).split(sep).join('/').replace(/index\.html$/, '');
  if (rel === 'product/') continue; // product pages are reached through the shop
  urls.push(`${SITE}/${rel}`);
}
urls.sort((a, b) => a.split('/').length - b.split('/').length || a.localeCompare(b));
writeFileSync(
  join(site, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${u}</loc></url>`)
    .join('\n')}\n</urlset>\n`,
);
console.log(`sitemap.xml: ${urls.length} pages`);

/* ---------- robots.txt ---------- */

writeFileSync(join(site, 'robots.txt'), `User-agent: *\nDisallow: /cart/\nDisallow: /checkout/\nDisallow: /pay/\n\nSitemap: ${SITE}/sitemap.xml\n`);
console.log('robots.txt written');
